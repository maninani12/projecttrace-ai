import {test,expect} from '@playwright/test'
import path from 'node:path'
test('upload → analyze → evidence → claims → question → viva → documentation',async({page})=>{
 await page.goto('/')
 await page.getByRole('button',{name:'View demo'}).click()
 await expect(page.getByRole('heading',{name:'Complaint workspace',exact:true})).toBeVisible({timeout:45000})
 await page.getByRole('button',{name:'Claim Ledger',exact:true}).click()
 await page.getByRole('button',{name:'Contradicted 1',exact:true}).click()
 await expect(page.getByText('The project uses MongoDB as its database.',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'The project uses MongoDB as its database.',exact:true}).click()
 await expect(page.getByLabel('Claim evidence inspector')).toContainText('PostgreSQL')
 await page.getByRole('button',{name:'Close inspector'}).click()
 await page.getByRole('button',{name:'Ask Project',exact:true}).click()
 await page.getByRole('button',{name:'Which database does this project use?'}).click()
 await expect(page.getByText('The project references PostgreSQL in its source or configuration.')).toBeVisible()
 await page.getByText('backend/database.py',{exact:true}).click()
 await page.getByRole('button',{name:'Open source'}).click()
 await expect(page.getByLabel('Source code')).toContainText('postgresql://')
 await page.getByRole('button',{name:'Viva',exact:true}).click()
 await page.getByRole('combobox',{name:'Examiner perspective'}).selectOption('ADVERSARIAL EXAMINER')
 await page.getByRole('button',{name:'Start practice'}).click()
 await expect(page.getByRole('heading',{name:/How would you explain the discrepancy/})).toBeVisible()
 await page.getByRole('button',{name:'Reveal suggested answer'}).click()
 await expect(page.getByText(/CONTRADICTED: The README names MongoDB/)).toBeVisible()
 await page.getByRole('button',{name:'Documentation',exact:true}).click()
 await page.getByRole('button',{name:'Generate draft'}).click()
 await expect(page.locator('.document-preview pre')).toContainText('Future Scope')
 await page.getByRole('button',{name:'Analyze project',exact:true}).click()
 await page.getByLabel('Project name',{exact:true}).fill('Uploaded evidence demo')
 await page.getByLabel('Repository ZIP').setInputFiles(path.resolve('../samples/mixed-demo.zip'))
 await page.getByRole('button',{name:'Start analysis'}).click()
 await expect(page.getByRole('heading',{name:'Uploaded evidence demo',exact:true})).toBeVisible({timeout:45000})
 await expect(page.getByText('PostgreSQL',{exact:true})).toBeVisible()
})
test('mobile navigation, theme and empty search stay usable',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto('/')
 await page.getByRole('button',{name:'View demo'}).click()
 await expect(page.getByRole('heading',{name:'Complaint workspace',exact:true})).toBeVisible({timeout:45000})
 await page.getByRole('button',{name:'Open navigation'}).click()
 await page.keyboard.press('Escape')
 await expect(page.locator('.sidebar')).toHaveAttribute('inert','')
 await expect(page.getByRole('button',{name:'Open navigation'})).toBeFocused()
 await page.getByRole('button',{name:'Open navigation'}).click()
 await page.getByRole('button',{name:'Claim Ledger',exact:true}).click()
 await page.getByRole('textbox',{name:'Search claims'}).fill('not-a-claim')
 await expect(page.getByText('No claims match this filter.')).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
})
